def selftest() -> int:
    problems: list[str] = []

    def fail(msg: str) -> None:
        problems.append(msg)

    def page(body: str, defs: str) -> str:
        return f"# T\n\n{body}\n{defs}"

    # The report's own example.
    p = page(
        "## Design rules\n\n"
        "The PDK's *Periphery rules* page gives difftap.3 = 0.270 "
        "µm.[^pdk-periph]\n",
        "[^pdk-periph]: SkyWater PDK, *Periphery rules*. "
        "<https://example.com/periph>\n",
    )
    new, counts = process_text(p)
    if counts.get("linked") != 1:
        fail(f"the report's own example did not link: {counts}")
    if "[*Periphery rules*](<https://example.com/periph>)" not in new:
        fail(f"wrong link produced: {new!r}")
    if "[^pdk-periph]" not in new:
        fail("the marker was disturbed")

    # Idempotent.
    new2, counts2 = process_text(new)
    if new2 != new or counts2.get("linked", 0):
        fail(f"not idempotent: {counts2}")

    # First occurrence per H2 only: a second co-occurrence of the same
    # title and marker in the same H2 is left alone.
    p = page(
        "## Design rules\n\n"
        "The PDK's *Periphery rules* page gives difftap.3 = 0.270 "
        "µm.[^pdk-periph] Later, the PDK's *Periphery rules* page also "
        "gives poly.2 = 0.210 µm.[^pdk-periph]\n",
        "[^pdk-periph]: SkyWater PDK, *Periphery rules*. "
        "<https://example.com/periph>\n",
    )
    new, counts = process_text(p)
    if counts.get("linked") != 1:
        fail(f"first-occurrence-per-H2 fired more than once: {counts}")
    if new.count("[*Periphery rules*]") != 1:
        fail(f"the second occurrence was linked too: {new!r}")
    # And running it again must not link the second occurrence either: an
    # already-linked occurrence still has to count as "seen" for its H2, or
    # a second run links the next occurrence down and ends up with two
    # links for one title in one H2 (found on docs/masks/pwdem.md, where
    # the site-wide run left the *second* Deep-dive-shaped mention in
    # "Drawn layers and derivation" for a later pass to wrongly pick up).
    new2, counts2 = process_text(new)
    if new2 != new or counts2.get("linked", 0):
        fail(f"a second run linked the later occurrence: {counts2} {new2!r}")

    # A new H2 gets its own first occurrence.
    p = page(
        "## A\n\nThe PDK's *Periphery rules* page gives one "
        "value.[^pdk-periph]\n\n"
        "## B\n\nThe PDK's *Periphery rules* page gives another "
        "value.[^pdk-periph]\n",
        "[^pdk-periph]: SkyWater PDK, *Periphery rules*. "
        "<https://example.com/periph>\n",
    )
    new, counts = process_text(p)
    if counts.get("linked") != 2:
        fail(f"a new H2 did not get its own first occurrence: {counts}")

    # Title and marker in *different* sentences: not linked.
    p = page(
        "## A\n\nThe PDK's *Periphery rules* page sets the design "
        "rules. A separate measurement confirms the value.[^pdk-periph]\n",
        "[^pdk-periph]: SkyWater PDK, *Periphery rules*. "
        "<https://example.com/periph>\n",
    )
    new, counts = process_text(p)
    if new != p or counts.get("linked", 0):
        fail(f"cross-sentence co-occurrence was wrongly linked: {new!r}")

    # Never inside a quotation.
    p = page(
        '## A\n\nThe filing states "see the *Periphery rules* page for '
        'details".[^pdk-periph]\n',
        "[^pdk-periph]: SkyWater PDK, *Periphery rules*. "
        "<https://example.com/periph>\n",
    )
    new, counts = process_text(p)
    if new != p or counts.get("linked", 0):
        fail(f"a title inside a quotation was linked: {new!r}")

    # Never inside a table (header or data row).
    p = page(
        "## A\n\n"
        "| Source | Note |\n"
        "|---|---|\n"
        "| The PDK's *Periphery rules* page | 0.270 µm.[^pdk-periph] |\n",
        "[^pdk-periph]: SkyWater PDK, *Periphery rules*. "
        "<https://example.com/periph>\n",
    )
    new, counts = process_text(p)
    if new != p or counts.get("linked", 0):
        fail(f"a title inside a table was linked: {new!r}")

    # Never inside a {dropdown}.
    p = page(
        "## A\n\n"
        ":::{dropdown} From a patent shown as in force (US 1,234,567; "
        "estimated expiry 2030-01-01) — open to read\n"
        "The PDK's *Periphery rules* page also matters here.[^pdk-periph]\n"
        ":::\n",
        "[^pdk-periph]: SkyWater PDK, *Periphery rules*. "
        "<https://example.com/periph>\n",
    )
    new, counts = process_text(p)
    if new != p or counts.get("linked", 0):
        fail(f"a title inside a dropdown was linked: {new!r}")

    # Never inside the generated index-links block.
    p = (
        "# T\n\n## A\n\n"
        "<!-- index-links:begin (generated by tools/gen_index_links.py; do not edit) -->\n"
        "### Related patents\n\n"
        "The PDK's *Periphery rules* page is cited here too.[^pdk-periph]\n"
        "<!-- index-links:end -->\n\n"
        "[^pdk-periph]: SkyWater PDK, *Periphery rules*. "
        "<https://example.com/periph>\n"
    )
    new, counts = process_text(p)
    if new != p or counts.get("linked", 0):
        fail(f"a title inside the generated block was linked: {new!r}")

    # Never in a paragraph next to a block quote (check_preserved.py's own
    # whitespace flattening can pair a quote mark in the block quote with
    # an unrelated one elsewhere on the page and read the paragraph in
    # between as part of a bogus "quotation" -- docs/machines/single-wafer
    # -spin-processor.md:161-166 is the real case that found this).
    p = page(
        'SkyWater\'s *Facilities & Capabilities* page lists:[^pdk-periph]\n\n'
        '> "Single Wafer"\n> "SEZ223, titration controlled"\n',
        "[^pdk-periph]: SkyWater PDK, *Facilities & Capabilities*. "
        "<https://example.com/periph>\n",
    )
    new, counts = process_text(p)
    if new != p or counts.get("linked", 0):
        fail(f"a paragraph beside a block quote was linked: {new!r}")

    # Never past "## References" (that's C1's territory).
    p = (
        "# T\n\n## References\n\n### Deep dive\n\n"
        "* The PDK's *Periphery rules* page — design rules.[^pdk-periph]\n\n"
        "[^pdk-periph]: SkyWater PDK, *Periphery rules*. "
        "<https://example.com/periph>\n"
    )
    new, counts = process_text(p)
    if new != p or counts.get("linked", 0):
        fail(f"a reading-list bullet was touched: {new!r}")

    # A prose bullet's own leading "* " is never mistaken for an italic
    # opening delimiter (it would otherwise "open" on the bullet marker
    # and "close" on the real title's own opening "*", eating it).
    p = page(
        "* The PDK's *Periphery rules* page gives a value.[^pdk-periph]\n",
        "[^pdk-periph]: SkyWater PDK, *Periphery rules*. "
        "<https://example.com/periph>\n",
    )
    new, counts = process_text(p)
    if counts.get("linked") != 1:
        fail(f"a prose bullet's leading '* ' broke italic matching: {counts}")
    if "[*Periphery rules*](<https://example.com/periph>)" not in new:
        fail(f"a prose bullet's title was mislinked: {new!r}")

    # A "**bold**" run near the marker is never mistaken for an italic
    # title (docs/steps/004-fom.md: "**The FOM reticle** ...[^thung-2016]"
    # next to an unrelated *Some paper* citation on the same page).
    p = page(
        "## A\n\n**The FOM reticle** is a chrome-on-quartz "
        "photomask.[^thung-2016] Elsewhere, *Some paper* gives a different "
        "value.[^some-paper]\n",
        "[^thung-2016]: Thung et al., *Some paper*. "
        "<https://example.com/thung>\n"
        "[^some-paper]: Thung et al., *Some paper*. "
        "<https://example.com/thung>\n",
    )
    new, counts = process_text(p)
    if "The FOM reticle" in "".join(
        m.group(1) for m in ITALIC_RE.finditer(new)
    ):
        fail(f"a bold run was matched as an italic title: {new!r}")
    if new.count("](<https://example.com/thung>)") != 1:
        fail(f"the real italic title was not linked exactly once: {new!r}")

    # A title wrapped across a line break is still matched.
    p = page(
        "## A\n\nThe PDK's *Periphery\nrules* page gives a "
        "value.[^pdk-periph]\n",
        "[^pdk-periph]: SkyWater PDK, *Periphery rules*. "
        "<https://example.com/periph>\n",
    )
    new, counts = process_text(p)
    if counts.get("linked") != 1:
        fail(f"a title wrapped across a line break was not linked: {counts}")
    if "[*Periphery\nrules*](<https://example.com/periph>)" not in new:
        fail(f"the wrapped title was mishandled: {new!r}")

    if problems:
        for p_ in problems:
            print("FAIL:", p_)
        return 1
    print("selftest OK")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="report only, write nothing")
    ap.add_argument("--selftest", action="store_true", help="run offline unit tests")
    ap.add_argument("paths", nargs="*")
    args = ap.parse_args()
    if args.selftest:
        return selftest()
    return run(args.paths, args.check)


if __name__ == "__main__":
    sys.exit(main())
