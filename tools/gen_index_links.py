STATUS_ORDER = ["in force", "unknown", "expired"]


def status_breakdown(fams: list[dict]) -> str:
    from collections import Counter
    c = Counter(gen_patents.status_word(f) for f in fams)
    return ", ".join(f"{c[s]} {s}" for s in STATUS_ORDER if c[s])


def expired_line(fam: dict) -> str:
    label = gen_patents.label_of(fam)
    pn = gen_patents.display_pn(gen_patents.rep_member(fam))
    year = str(fam["dates"]["priority"])[:4]
    title = fam["title"]
    if "<" in title or ">" in title:
        # A literal "<...>" in the title (crystal-plane notation, e.g.
        # "<100>") cannot sit inside a {ref} role's own "<target>"
        # delimiter, even backslash-escaped: MyST's target regex runs
        # before escape processing. Fall back to number-first for just
        # this case rather than break the link.
        return f"* {{ref}}`{pn} <{label}>` — {gen_patents.esc(title)} ({year})"
    return f"* {{ref}}`{gen_patents.esc(title)} <{label}>` — {pn} ({year})"


def render_patents(fams: list[dict]) -> list[str]:
    if not fams:
        return []
    if len(fams) > THRESHOLD:
        return [
            f"**Related patents.** {gen_patents.plural(len(fams), 'family')} concern this page "
            f"({status_breakdown(fams)}).",
            "",
            "See {ref}`patents-by-module` for the full, grouped list "
            "(families still in force or of unknown status are collapsed there too).",
        ]
    expired = [f for f in fams if f["expired"] is True]
    collapsed = [f for f in fams if f["expired"] is not True]
    lines = ["**Related patents.**", ""]
    for f in expired:
        lines.append(expired_line(f))
    if collapsed:
        if expired:
            lines.append("")
        lines.append(f":::{{dropdown}} {gen_patents.plural(len(collapsed), 'family')} in force or status unknown")
        lines.append("")
        lines.append("Status and expiry are estimates from public records and are not legal advice.")
        lines.append("")
        for f in collapsed:
            lines.append(gen_patents.family_link_line(f))
        lines.append(":::")
    return lines


def render_papers(papers: list[dict]) -> list[str]:
    if not papers:
        return []
    if len(papers) > THRESHOLD:
        return [
            f"**Related papers.** {gen_papers.plural(len(papers))} relate to this page.",
            "",
            "See {ref}`papers-by-module` for the full, grouped list.",
        ]
    lines = ["**Related papers.**", ""]
    for p in papers:
        lines.append(gen_papers.line(p))
    return lines


def render_filings(filings: list[dict]) -> list[str]:
    if not filings:
        return []
    if len(filings) > THRESHOLD:
        return [
            f"**Related filings.** {gen_filings.plural(len(filings), 'filing')} relate to this page.",
            "",
            "See {ref}`filings-by-relationship` for the full, grouped list.",
        ]
    lines = ["**Related filings.**", ""]
    for f in filings:
        lines.append(gen_filings.short_line(f))
    return lines


def heading_for(path: Path) -> str:
    """The heading that introduces the block (report-A F13, report-B
    B11), as an H3: step pages get step-specific wording, every other
    page type gets the generic form. The block always lands
    immediately before "## References" (see apply_block/module
    docstring). On a page whose last H2 before that point is itself a
    "Related …" section (step pages' "Related steps and
    cross-references", or "Related pages" on machine/material/mask
    pages), an H3 correctly nests under it, which is where F13 asks for
    it to fall. See ``heading_level()`` for pages where it does not."""
    kind = path.relative_to(DOCS).parts[0]
    if kind == "steps":
        return "### Patents, papers and filings about this step"
    return "### Related patents, papers and filings"


def heading_level(stripped_text: str, path: Path) -> str:
    """``heading_for(path)``, downgraded from H3 to H2 where nesting it
    under the preceding H2 would be false (review H1): report-B B11
    named exactly this — on the 10 category pages, the two overview
    pages and the machines/materials/masks *index* pages, the block's
    H2 predecessor is unrelated ("Steps in this category", "Key open
    questions", "Safety and abatement", …), so an H3 there reads as a
    false child of that section rather than its own topic. Where the
    preceding H2 already starts "Related" (step pages, and the
    machine/material/mask *class* pages, whose H2 is "Related pages"),
    the H3 nests correctly and is left alone. ``stripped_text`` is the
    page text with any existing generated block already removed, so a
    stale block's own heading is never mistaken for page content."""
    idx = stripped_text.find(f"\n{REF_HEADING}\n")
    before = stripped_text[:idx] if idx != -1 else stripped_text
    h2s = [line for line in before.splitlines() if line.startswith("## ")]
    heading = heading_for(path)
    if h2s and h2s[-1].startswith("## Related"):
        return heading
    return heading[1:]  # "### ..." -> "## ..."


LABEL_ONLY_RE = re.compile(r"^\*\*Related \w+\.\*\*$")
LABEL_PREFIX_RE = re.compile(r"^\*\*Related \w+\.\*\* ")


def drop_redundant_label(part: list[str]) -> list[str]:
    """Remove a dataset's own bold "**Related X.**" lead-in when it is
    the only dataset in the block (review L3): the heading above it
    already says "Patents, papers and filings" (or the step-specific
    form), so repeating "Related patents." immediately under it reads
    as the same label twice. Only used when ``len(parts) == 1`` in
    ``render_block()``; with two or three datasets each lead-in still
    tells them apart and is left alone."""
    if not part:
        return part
    if LABEL_ONLY_RE.match(part[0]):
        rest = part[1:]
        if rest[:1] == [""]:
            rest = rest[1:]
        return rest
    return [LABEL_PREFIX_RE.sub("", part[0], count=1), *part[1:]]


def render_block(data: dict[str, list], heading: str) -> str:
    parts = [p for p in (render_patents(data["patents"]), render_papers(data["papers"]),
                          render_filings(data["filings"])) if p]
    if not parts:
        return ""
    if len(parts) == 1:
        parts = [drop_redundant_label(parts[0])]
    lines: list[str] = [heading, ""]
    for i, part in enumerate(parts):
        if i:
            lines.append("")
        lines.extend(part)
    return "\n".join(lines)


def block_text(content: str) -> str:
    return f"{MARK_BEGIN}\n{content}\n{MARK_END}"


# ---------------------------------------------------------------------------
# Splicing into a page
# ---------------------------------------------------------------------------

def strip_existing(text: str) -> str:
    """Remove an existing generated block (and the blank lines around it),
    collapsing to a single blank line, wherever it is in the file."""
    return BLOCK_STRIP_RE.sub("\n\n", text)


def apply_block(text: str, content: str, where: str) -> str:
    text = strip_existing(text)
    marker = f"\n{REF_HEADING}\n"
    idx = text.find(marker)
    if idx == -1:
        raise SystemExit(f"{where}: no '{REF_HEADING}' heading found")
    if text.find(marker, idx + 1) != -1:
        raise SystemExit(f"{where}: more than one '{REF_HEADING}' heading found")
    before = text[:idx].rstrip("\n")
    after_heading = text[idx + 1:]
    if content:
        return before + "\n\n" + block_text(content) + "\n\n" + after_heading
    return before + "\n\n" + after_heading


