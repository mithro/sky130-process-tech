def _fam(id_, expired, priority="2005-01-01", pn="US10000000B2", title="A widget", status="Active"):
    return {
        "id": id_,
        "representative": pn,
        "title": title,
        "dates": {"priority": priority, "filing": priority, "grant": priority},
        "legal_status": {"status": status, "source": "test"},
        "expiry": {"date": "2025-01-01", "estimated": True, "basis": "test"},
        "expired": expired,
        "members": [{"number": pn, "country": "US", "kind": "B2",
                     "links": {"espacenet": "https://x", "google_patents": "https://y"}}],
        "relevance": [{"target": "step-999", "relation": "cited-on-page", "reason": "Test reason."}],
    }


def _paper(id_, label):
    return {"id": id_, "label": label, "authors": ["Smith, A."], "venue_series": "TED", "year": 2020,
            "title_display": "A test paper", "free_full_text": [], "basis": "named-process"}


def _filing(id_):
    return {"id": id_, "company": "Test Co.", "form": "10-K", "filed": "2020-01-01", "title": "Annual report"}


def selftest() -> int:
    problems = []

    # 1. Splicing: insertion before "## References", exactly one blank line
    #    on each side, and idempotent on a no-op re-apply.
    page = "# Title\n\nSome text.\n\n## References\n\n### Cross-check\n"
    once = apply_block(page, "**Related patents.**\n* a link", "test")
    expect = ("# Title\n\nSome text.\n\n" + block_text("**Related patents.**\n* a link") +
              "\n\n## References\n\n### Cross-check\n")
    if once != expect:
        problems.append(f"splice mismatch:\n{once!r}\nexpected:\n{expect!r}")
    twice = apply_block(once, "**Related patents.**\n* a link", "test")
    if twice != once:
        problems.append("re-applying the same content is not a no-op")

    # 2. Removing a block when the page no longer qualifies.
    removed = apply_block(once, "", "test")
    if removed != "# Title\n\nSome text.\n\n## References\n\n### Cross-check\n":
        problems.append(f"block removal left residue:\n{removed!r}")

    # 3. Threshold: <=12 lists everything, >12 collapses to a count line
    #    and a separate link line (report-A F13: "split the count-only
    #    sentence").
    fams13 = [_fam(f"GP{i}", True) for i in range(13)]
    block13 = render_patents(fams13)
    if not any("patents-by-module" in l for l in block13):
        problems.append("13 families did not collapse to a by-module link")
    if any("patent-gp" in l for l in block13):
        problems.append("13-family collapsed block still names a family")
    count_line = next((i for i, l in enumerate(block13) if "concern this page" in l), None)
    link_line = next((i for i, l in enumerate(block13) if "patents-by-module" in l), None)
    if count_line is None or link_line is None or link_line <= count_line or block13[count_line + 1] != "":
        problems.append(f"count line and link line are not split onto their own lines: {block13!r}")
    fams12 = [_fam(f"GP{i}", True) for i in range(12)]
    block12 = render_patents(fams12)
    if not all(f"patent-gp{i}" in "\n".join(block12) for i in range(12)):
        problems.append("12 families did not all appear in the list form")

    # 4. Expired vs. collapsed split and dropdown wording.
    mixed = [_fam("GP1", True), _fam("GP2", False), _fam("GP3", "unknown")]
    block = "\n".join(render_patents(mixed))
    if "patent-gp1" not in block or ":::{dropdown}" not in block:
        problems.append("mixed expired/collapsed rendering missing a part")
    if "2 families in force or status unknown" not in block:
        problems.append("dropdown title wording wrong")
    if "patent-gp2" not in block or "patent-gp3" not in block:
        problems.append("collapsed families not linked inside the dropdown")
    if "not legal advice" not in block:
        problems.append("collapsed dropdown missing the estimate/not-legal-advice sentence")

    # 4b. Expired-family link text is title-first, number after (F13);
    #     a title containing a literal "<...>" falls back to number-first
    #     so the {ref} role's own "<target>" delimiter is unambiguous.
    plain = expired_line(_fam("GP9", True, title="A widget"))
    if not plain.startswith("* {ref}`A widget <patent-gp9>` — US 10,000,000 B2 ("):
        problems.append(f"expired_line is not title-first: {plain!r}")
    angled = expired_line(_fam("GP8", True, title="Has a <100> plane"))
    if not angled.startswith("* {ref}`US 10,000,000 B2 <patent-gp8>` — "):
        problems.append(f"expired_line did not fall back for a title with '<...>': {angled!r}")

    # 4c. heading_for(): step-specific wording vs. the generic form, and
    #     render_block() puts it first, only when there is content.
    step_h = heading_for(DOCS / "steps" / "001-smat.md")
    other_h = heading_for(DOCS / "machines" / "index.md")
    if step_h != "### Patents, papers and filings about this step":
        problems.append(f"wrong step-page heading: {step_h!r}")
    if other_h != "### Related patents, papers and filings":
        problems.append(f"wrong non-step-page heading: {other_h!r}")
    headed = render_block({"patents": [_fam("GP7", True)], "papers": [], "filings": []}, step_h)
    if not headed.startswith(step_h + "\n\n"):
        problems.append(f"render_block did not lead with the heading: {headed!r}")

    # 4d. heading_level(): H3 kept only when it would nest under a
    # "Related ..." H2; downgraded to H2 otherwise (review H1).
    related_page = "# Title\n\n## Related pages\n\nSome text.\n\n## References\n\n### Cross-check\n"
    unrelated_page = "# Title\n\n## Steps in this category\n\nSome text.\n\n## References\n\n### Cross-check\n"
    machines_index_path = DOCS / "machines" / "index.md"
    lvl_related = heading_level(related_page, machines_index_path)
    lvl_unrelated = heading_level(unrelated_page, DOCS / "categories" / "cmp.md")
    if lvl_related != other_h:
        problems.append(f"heading_level downgraded an H3 that nests correctly: {lvl_related!r}")
    if lvl_unrelated != "## Related patents, papers and filings":
        problems.append(f"heading_level did not downgrade a false H3 nesting: {lvl_unrelated!r}")
    # A stale block already in the text must not be mistaken for a
    # "## Related ..." predecessor once strip_existing() removes it.
    stale = apply_block(unrelated_page, "### Some stale heading\n\nstuff", "test")
    lvl_after_stale = heading_level(strip_existing(stale), DOCS / "categories" / "cmp.md")
    if lvl_after_stale != "## Related patents, papers and filings":
        problems.append(f"heading_level was fooled by a stale block: {lvl_after_stale!r}")

    # 4e. render_block() drops the redundant "**Related X.**" lead-in
    # when only one dataset is present (review L3), in both the list
    # form and the >THRESHOLD count-sentence form; with two datasets
    # both lead-ins stay so the reader can tell them apart.
    one_list = render_block({"patents": [_fam("GP10", True)], "papers": [], "filings": []}, other_h)
    if "**Related patents.**" in one_list:
        problems.append(f"single-dataset block kept the redundant label: {one_list!r}")
    if "patent-gp10" not in one_list:
        problems.append(f"dropping the label lost the list itself: {one_list!r}")
    fams13 = [_fam(f"GP1{i}", True) for i in range(13)]
    one_over = render_block({"patents": fams13, "papers": [], "filings": []}, other_h)
    if "**Related patents.**" in one_over:
        problems.append(f"single-dataset over-threshold block kept the redundant label: {one_over!r}")
    if "concern this page" not in one_over:
        problems.append(f"dropping the label lost the count sentence: {one_over!r}")
    two = render_block({"patents": [_fam("GP20", True)], "papers": [_paper("doi:2", "paper-y-2021a")],
                         "filings": []}, other_h)
    if "**Related patents.**" not in two:
        problems.append(f"two-dataset block dropped a lead-in it should have kept: {two!r}")

    # 5. Papers and filings render at all, and also collapse over threshold.
    p_block = render_papers([_paper("doi:1", "paper-x-2020a")])
    if not any("paper-x-2020a" in l for l in p_block):
        problems.append("paper line missing")
    p_over = render_papers([_paper(f"doi:{i}", f"paper-x-2020{chr(97+i)}") for i in range(13)])
    if not any("papers-by-module" in l for l in p_over):
        problems.append("13 papers did not collapse to a by-module link")
    f_block = render_filings([_filing("f-1")])
    if not any("f-1" in l for l in f_block):
        problems.append("filing line missing")
    f_over = render_filings([_filing(f"f-{i}") for i in range(13)])
    if not any("filings-by-relationship" in l for l in f_over):
        problems.append("13 filings did not collapse to a by-relationship link")

    # 6. Empty input renders nothing (not even the heading).
    if render_block({"patents": [], "papers": [], "filings": []}, other_h) != "":
        problems.append("empty data did not render an empty block")

    if problems:
        for p in problems:
            print("SELFTEST FAIL:", p)
        print(f"{len(problems)} selftest problem(s)")
        return 1
    print("selftest OK")
    return 0


