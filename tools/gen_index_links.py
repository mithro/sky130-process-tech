def candidate_pages(labels: dict[str, Path], targets: dict[Path, dict[str, list]]) -> set[Path]:
    """Every page that should have a block, plus every page that currently
    has one (so a block can be removed when a page no longer qualifies)."""
    pages = set(targets)
    for path in DOCS.rglob("*.md"):
        rel = path.relative_to(DOCS).as_posix()
        if rel.startswith("plans/") or rel.startswith("_build/") or not in_scope(path):
            continue
        if MARK_BEGIN in path.read_text(encoding="utf-8"):
            pages.add(path)
    return pages


def generate() -> dict[Path, str]:
    """Return {page path: new file text} for every page that should be
    written (i.e. whose text actually changes)."""
    labels = check_patents.doc_labels()
    fams = load_families()
    papers = load_papers()
    filings = load_filings()
    targets = build_targets(labels, fams, papers, filings)
    empty: dict[str, list] = {"patents": [], "papers": [], "filings": []}
    out: dict[Path, str] = {}
    for path in sorted(candidate_pages(labels, targets)):
        data = targets.get(path, empty)
        old_text = path.read_text(encoding="utf-8")
        heading = heading_level(strip_existing(old_text), path)
        content = render_block(data, heading)
        new_text = apply_block(old_text, content, str(path.relative_to(ROOT)))
        if new_text != old_text:
            out[path] = new_text
    return out


def summary(labels: dict[str, Path], fams: list[dict], papers: list[dict], filings: list[dict],
            targets: dict[Path, dict[str, list]]) -> str:
    n_steps = sum(1 for p in targets if p.relative_to(DOCS).parts[0] == "steps")
    n_machines = sum(1 for p in targets if p.relative_to(DOCS).parts[0] == "machines")
    n_materials = sum(1 for p in targets if p.relative_to(DOCS).parts[0] == "materials")
    n_categories = sum(1 for p in targets if p.relative_to(DOCS).parts[0] == "categories")
    n_masks = sum(1 for p in targets if p.relative_to(DOCS).parts[0] == "masks")
    n_overview = sum(1 for p in targets if p.relative_to(DOCS).parts[0] == "overview")
    all_fams = {f["id"] for d in targets.values() for f in d["patents"]}
    all_papers = {p["id"] for d in targets.values() for p in d["papers"]}
    all_filings = {f["id"] for d in targets.values() for f in d["filings"]}
    return (f"{len(targets)} pages linked (steps {n_steps}, machines {n_machines}, "
            f"materials {n_materials}, categories {n_categories}, masks {n_masks}, "
            f"overview {n_overview}); {len(all_fams)} patent families, {len(all_papers)} papers, "
            f"{len(all_filings)} filings referenced")


def stale_pages_in(dir_name: str) -> list[str]:
    """One problem string per page under ``docs/<dir_name>/`` whose
    generated index-links block is missing, stale or was hand-edited.

    Shared by ``check_steps.py``, ``check_machines.py``,
    ``check_materials.py`` and ``check_masks.py`` (progress file item 8)
    so the diff logic that decides "stale or hand-edited" lives in one
    place instead of four copies of it."""
    changes = generate()
    prefix = f"{dir_name}/"
    problems = []
    for p in sorted(changes):
        rel = p.relative_to(DOCS).as_posix()
        if rel.startswith(prefix):
            problems.append(
                f"{p.relative_to(ROOT)}: index-links block missing, stale or hand-edited "
                "(run `uv run tools/gen_index_links.py`)"
            )
    return problems


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if any page's block is missing, stale or hand-edited")
    ap.add_argument("--selftest", action="store_true", help="run the offline self-test and exit; touches no files")
    args = ap.parse_args()

    if args.selftest:
        return selftest()

    labels = check_patents.doc_labels()
    fams = load_families()
    papers = load_papers()
    filings = load_filings()
    targets = build_targets(labels, fams, papers, filings)
    changes = generate()

    if args.check:
        if changes:
            for path in sorted(changes):
                print(f"{path.relative_to(ROOT)}: block missing, stale or hand-edited")
            print(f"{len(changes)} page(s) differ. {summary(labels, fams, papers, filings, targets)}")
            return 1
        print(f"0 pages differ. {summary(labels, fams, papers, filings, targets)}")
        return 0

    for path, text in changes.items():
        path.write_text(text, encoding="utf-8")
    verb_count = len(changes)
    print(f"{verb_count} page(s) written. {summary(labels, fams, papers, filings, targets)}")
    return 0


